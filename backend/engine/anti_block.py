def get_random_ua() -> str:
    """Return a random User-Agent string."""
    return random.choice(USER_AGENTS)


async def random_delay(min_sec: float = 5.0, max_sec: float = 15.0) -> None:
    """Sleep for a random duration between min_sec and max_sec (jitter)."""
    delay = random.uniform(min_sec, max_sec)
    await asyncio.sleep(delay)


def get_proxy_settings() -> dict | None:
    """
    Read proxy configuration from environment variables.
    Returns a Playwright-compatible proxy dict or None.
    """
    proxy_url = os.environ.get("HTTP_PROXY") or os.environ.get("HTTPS_PROXY")
    if not proxy_url:
        return None
    proxy = {"server": proxy_url}
    proxy_user = os.environ.get("PROXY_USERNAME")
    proxy_pass = os.environ.get("PROXY_PASSWORD")
    if proxy_user:
        proxy["username"] = proxy_user
    if proxy_pass:
        proxy["password"] = proxy_pass
    return proxy


